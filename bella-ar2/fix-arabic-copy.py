# ---------------------------------------------------------------- run
hits, misses = 0, []
for path in sorted(glob.glob(os.path.join(SRC, "*.html"))):
    name = os.path.basename(path)
    h = io.open(path, encoding="utf-8").read()
    pairs = list(GLOBAL) + PER_FILE.get(name, []) + (INDEX if name == "index.html" else [])
    n = 0
    for old, new in pairs:
        if old in h:
            h = h.replace(old, new); n += h.count(new) and 1
    for old, new in PER_FILE.get(name, []):
        if old not in io.open(path, encoding="utf-8").read() and new not in h:
            misses.append(f"{name}: {old[:45]}")
    io.open(os.path.join(OUT, name), "w", encoding="utf-8").write(h)
    hits += n

print(f"files written: {len(glob.glob(os.path.join(OUT,'*.html')))}")
if misses:
    print("\nNOT FOUND (check manually):")
    for m in misses: print("  " + m)
else:
    print("every targeted phrase matched")
